"""Generate tools/test/questiedb_mock.lua: a small LibQuestieDB stand-in for the smoke tests.

Usage: python3 -I tools/test/gen_questiedb_mock.py raw.json tools/test/questiedb_mock.lua
(raw.json is the output of tools/data/extract.py.)
"""
import sys, json

raw = json.load(open(sys.argv[1]))
OUT = sys.argv[2]


def lua(v):
    if v is None:
        return 'nil'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'
    if isinstance(v, list):
        return '{' + ', '.join(lua(x) for x in v) + '}'
    if isinstance(v, dict):
        return '{' + ', '.join('[%s] = %s' % (lua(k), lua(x)) for k, x in v.items()) + '}'
    raise TypeError(v)


items, npcs, quests, area_to_map = {}, {}, {}, {}
for iid, it in raw['items'].items():
    drops = [d['id'] for d in it['dropNpcs']]
    items[int(iid)] = {'vendors': it['vendors'] or None, 'questRewards': it['quests'] or None,
                       'npcDrops': drops or None}
    for d in it['dropNpcs']:
        area = 100000 + (d['zone'] or 0)  # synthetic area id for the drop NPC's zone
        if d['zone']:
            area_to_map[area] = d['zone']
        npcs.setdefault(d['id'], {'name': d['name'], 'minLevel': d['minLevel'], 'maxLevel': d['maxLevel'],
                                  'zoneID': area})
for nid, n in raw['npcs'].items():
    spawns = {}
    for area, ui, x, y in n['spawns']:
        if ui:
            area_to_map[area] = ui
        spawns.setdefault(area, []).append([x, y])
    rec = npcs.setdefault(int(nid), {'minLevel': 30, 'maxLevel': 30, 'zoneID': 0})
    rec.update({'name': n['name'], 'subName': n['title'], 'friendlyToFaction': n['faction'],
                'spawns': spawns or None})
for qid, q in raw['quests'].items():
    quests[int(qid)] = {'name': q['name'], 'questLevel': q['level'], 'requiredLevel': q['req'],
                        'requiredRaces': q['races'] or 0, 'requiredClasses': q['classes'] or 0}

zone_str = 'return ' + lua(area_to_map)
out = ['-- AUTO-GENERATED by tools/test/gen_questiedb_mock.py (test data, not shipped with the addon).',
       'local items, npcs, quests = %s, %s, %s' % (lua(items), lua(npcs), lua(quests)),
       '''
local NUMERIC = { minLevel = true, maxLevel = true, zoneID = true, questLevel = true, requiredLevel = true,
  requiredRaces = true, requiredClasses = true }
local function Entity(rows)
  return setmetatable({ Exists = function(id) return rows[id] ~= nil end }, { __index = function(_, field)
    return function(id)
      local row = rows[id]
      if not row then return nil end
      local v = row[field]
      if v == nil and NUMERIC[field] then return 0 end
      return v
    end
  end })
end

LibQuestieDB = {
  contractVersion = 4,
  RequireContract = function(v) return v >= 1 and v <= 4 end,
  l10n = { currentLocale = "enUS" },
  Item = Entity(items), Npc = Entity(npcs), Quest = Entity(quests),
  Support = { Get = function(name)
    if name == "ZoneDB" then return { private = { areaIdToUiMapId = %s } } end
  end },
}
function LibQuestieDB.l10n.SetLocale(locale) LibQuestieDB.l10n.currentLocale = locale end
''' % lua(zone_str)]
open(OUT, 'w').write('\n'.join(out))
print(len(items), 'items,', len(npcs), 'npcs,', len(quests), 'quests')
